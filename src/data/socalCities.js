const JITTER_SEED = {};
function stableJitter(key, index) {
  const k = `${key}-${index}`;
  if (!JITTER_SEED[k]) {
    JITTER_SEED[k] = { lat: (Math.random() - 0.5) * 0.04, lng: (Math.random() - 0.5) * 0.04 };
  }
  return JITTER_SEED[k];
}

export function getProjectCoords(project, indexInCity = 0) {
  if (project.lat && project.lng) return [project.lat, project.lng];
  const key = (project.city || '').toLowerCase().trim();
  const entry = SOCAL_CITIES[key];
  if (!entry) return null;
  const j = stableJitter(key, indexInCity);
  return [entry.lat + j.lat, entry.lng + j.lng];
}

export function getProjectCounty(project) {
  const key = (project.city || '').toLowerCase().trim();
  return SOCAL_CITIES[key]?.county || 'Unknown';
}

export function getCountyStats(projects) {
  const total = projects.length;
  const counts = {};
  for (const p of projects) {
    const county = getProjectCounty(p);
    counts[county] = (counts[county] || 0) + 1;
  }
  return Object.entries(counts)
    .sort((a, b) => b[1] - a[1])
    .map(([county, count]) => ({
      county,
      count,
      pct: total > 0 ? Math.round(count / total * 100) : 0,
      color: COUNTY_COLORS[county] || '#555',
    }));
}
